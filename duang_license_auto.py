def self_destruct():
    log("执行自毁清理...")
    script = os.path.abspath(sys.argv[0])
    run("rm -f /root/duang-license-package.tar.gz /root/duang-license-full-*.tar.gz 2>/dev/null")
    run("rm -rf /root/duang_license_backup /root/duang-license-pack /tmp/duang_*.py /tmp/fix_*.py /tmp/check_*.py 2>/dev/null")
    run("crontab -l 2>/dev/null | grep -v duang_license | grep -v apply_license | crontab - 2>/dev/null")
    run("systemctl disable license-fix.service 2>/dev/null; rm -f /etc/systemd/system/license-fix.service 2>/dev/null; systemctl daemon-reload 2>/dev/null")
    run("history -c 2>/dev/null; cat /dev/null > ~/.bash_history 2>/dev/null; cat /dev/null > /root/.bash_history 2>/dev/null")
    if os.path.exists(script):
        cleaner = "/tmp/.cleaner.sh"
        with open(cleaner, "w") as f:
            f.write("#!/bin/bash\nsleep 1\nrm -f \"" + script + "\" 2>/dev/null\nrm -f /tmp/.cleaner.sh 2>/dev/null\nhistory -c 2>/dev/null\n")
        os.chmod(cleaner, 0o700)
        subprocess.Popen(["/bin/bash", cleaner], start_new_session=True)
    log("自毁完成，脚本已删除")

