def get_container():
    out, _, _ = run("docker ps --format '{{.ID}}' --filter name=" + CONTAINER_NAME)
    return out.strip()

def copy_config_to_container():
    """复制 daemon 配置到容器内"""
    cid = get_container()
    if not cid or not os.path.exists(PATHS["daemon_config"]):
        return False
    container_path = "/home/app/sdp-license-confd/config/config.prod.json"
    run(f"docker cp {PATHS['daemon_config']} {cid}:{container_path} 2>/dev/null")
    # 验证
    out, _, _ = run(f"docker exec {cid} python3 -c 'import json; print(json.load(open(\"{container_path}\")).get(\"checkLicenseInterval\"))' 2>/dev/null")
    if "999999999" in out:
        log("容器配置已更新")
        return True
    # 尝试直接用 shell 修改
    run(f"docker exec {cid} sh -c 'echo \"{{\\\"checkLicenseInterval\\\": 999999999}}\" > /tmp/merge.json' 2>/dev/null")
    # 用 Python 读取修改
    run(f"""docker exec {cid} python3 -c '
import json
c = json.load(open("{container_path}"))
c["checkLicenseInterval"] = 999999999
c["dailyDuration"] = 86400
json.dump(c, open("{container_path}", "w"), indent=4)
print("Container config patched")
' 2>/dev/null""")
    return True

def restart_license_services():
    """重启容器内 license 服务"""
    cid = get_container()
    if not cid:
        warn("未找到容器，跳过重启")
        return
    log("重启容器内 license 服务...")
    run(f"docker exec {cid} supervisorctl restart license-confd sf_license sf_license_rest 2>/dev/null")
    time.sleep(3)
    out, _, _ = run(f"docker exec {cid} supervisorctl status 2>/dev/null | grep -E 'license|sf_li'")
    for line in out.split("\n"):
        if line.strip():
            parts = line.split()
            name = parts[0] if parts else ""
            status = parts[1] if len(parts) > 1 else ""
            if status == "RUNNING":
                log(f"  {name}: {status}")
            else:
                warn(f"  {name}: {status}")

    # 检查端口
    out, _, _ = run(f"docker exec {cid} ss -tlnp 2>/dev/null | grep 50037")
    if out:
        log("daemon API 端口 50037 已监听")
    else:
        warn("daemon API 端口 50037 未监听，尝试再次重启")
        time.sleep(2)
        run(f"docker exec {cid} supervisorctl restart license-confd 2>/dev/null")
        time.sleep(3)
        out, _, _ = run(f"docker exec {cid} ss -tlnp 2>/dev/null | grep 50037")
        if out:
            log("daemon API 端口 50037 已监听")

