def main():
    print("\n" + "=" * 60)
    print("  Duang 授权自动化脚本 v2.0")
    print("  适用于 aTrust / PlatOS 系统")
    print("=" * 60)
    
    args = sys.argv[1:]
    self_destruct_mode = "--self-destruct" in args
    url = None
    
    for i, arg in enumerate(args):
        if arg.startswith("--url="):
            url = arg.split("=", 1)[1]
        elif arg == "--url" and i + 1 < len(args):
            url = args[i + 1]
    
    if "--collect-only" in args:
        run("echo 'collect mode not implemented in v2, use v1'")
        return
    
    # Step 1: 确保 .lic 文件存在
    if not os.path.exists(PATHS["lic_file"]):
        warn(".lic 文件不存在")
        if url:
            log("尝试从云端下载授权包...")
            pkg = download_package(url)
            if pkg:
                extract_and_install(pkg)
        if not os.path.exists(PATHS["lic_file"]):
            log("生成最小 .lic 文件...")
            generate_minimal_lic()
    else:
        log(f".lic 文件已存在: {PATHS['lic_file']}")
    
    # Step 2: 修改 daemon 配置
    fix_daemon_config()
    
    # Step 3: 修改 etcd 数据
    apply_etcd_license()
    
    # Step 4: 重启服务
    restart_license_services()
    
    # Step 5: 验证
    time.sleep(2)
    if verify():
        log("授权修改成功！请刷新 Web 页面查看")
    else:
        warn("授权验证有异常，请检查")
    
    # 自毁
    if self_destruct_mode:
        self_destruct()

if __name__ == "__main__":
    main()
