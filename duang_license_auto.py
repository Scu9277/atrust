def download_package(url):
    log(f"从云端下载授权包...")
    tmp = f"/tmp/duang_pkg_{int(time.time())}.tar.gz"
    out, err, rc = run(f"curl -sLk -o {tmp} --connect-timeout 30 '{url}' 2>/dev/null")
    if rc != 0 or not os.path.exists(tmp) or os.path.getsize(tmp) == 0:
        out, err, rc = run(f"wget -q -O {tmp} '{url}' 2>/dev/null")
    if not os.path.exists(tmp) or os.path.getsize(tmp) == 0:
        error("下载授权包失败")
        return None
    log(f"下载成功 ({os.path.getsize(tmp)} bytes)")
    return tmp

def extract_and_install(tarball):
    """解压并安装授权包到系统"""
    log("安装授权包...")
    extract_dir = tempfile.mkdtemp(prefix="duang_")
    try:
        with tarfile.open(tarball, "r:gz") as tar:
            tar.extractall(extract_dir)
        
        # 找到实际内容目录
        base = extract_dir
        items = os.listdir(base)
        if len(items) == 1 and os.path.isdir(os.path.join(base, items[0])):
            base = os.path.join(base, items[0])
        
        # 复制 .lic 文件
        lic_src = os.path.join(base, "license", "sf_license.lic")
        if os.path.exists(lic_src):
            os.makedirs(PATHS["lic_dir"], exist_ok=True)
            shutil.copy2(lic_src, PATHS["lic_file"])
            log(f".lic 文件已安装")
        
        # 复制 conf
        conf_src = os.path.join(base, "license", "sf_license_conf.json")
        if os.path.exists(conf_src):
            shutil.copy2(conf_src, PATHS["lic_conf"])
        
        # 复制 auth keys
        for fname in ["auth_encode.key", "auth_encode.iv"]:
            src = os.path.join(base, "app-secret", fname)
            if os.path.exists(src):
                os.makedirs(os.path.dirname(PATHS["auth_key"]), exist_ok=True)
                shutil.copy2(src, os.path.join(os.path.dirname(PATHS["auth_key"]), fname))
        
        # 复制 fingerprint
        fp_src = os.path.join(base, "fingerprint", "atrust_deivce_fingerprint.pub")
        if os.path.exists(fp_src):
            shutil.copy2(fp_src, PATHS["fingerprint"])
        
        # 复制 daemon config
        dc_src = os.path.join(base, "config.prod.json")
        if os.path.exists(dc_src):
            shutil.copy2(dc_src, PATHS["daemon_config"])
            log(f"daemon 配置文件已安装")
        
        # 复制 etcd 数据（备用）
        etcd_src = os.path.join(base, "etcd_license.json")
        if os.path.exists(etcd_src):
            shutil.copy2(etcd_src, PATHS["lic_dir"] + "etcd_license.json")
        
        log("授权包安装完成")
        return True
    except Exception as e:
        error(f"安装授权包失败: {e}")
        return False
    finally:
        shutil.rmtree(extract_dir, ignore_errors=True)
        if tarball.startswith("/tmp/"):
            try: os.remove(tarball)
            except: pass

