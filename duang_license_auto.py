def apply_etcd_license():
    log("修改 etcd 授权数据...")
    ETCD = PATHS["etcdctl"]
    
    out, err, rc = run(f"{ETCD} get /config/private/license/local --print-value-only")
    if rc != 0 or not out:
        error(f"读取 etcd 失败: {err}")
        return False
    
    try:
        data = json.loads(out)
    except:
        error("etcd 数据解析失败")
        return False
    
    L = data["license"]
    L["licenseType"] = LICENSE_TYPE
    L["customerName"] = CUSTOMER_NAME
    L["status"] = "activated"
    L["sn"] = SERIAL_NUMBER
    L["licno"] = "DUANG-CLOUD-999999"
    
    Y = EXPIRE_YEAR_2200
    for m in ["base","uem","emm","virtualNet","appWrap","omniscient","skyInspect"]:
        if m not in L: continue
        ke = m + "ExpireTime" if m != "base" else "baseExpireTime"
        ku = m + "IsUnlimited" if m != "base" else "baseIsUnlimited"
        L[m][ke] = Y; L[m][ku] = True
        for p in (L[m].get("parts") or []):
            p["expireTime"] = Y; p["isUnlimited"] = True; p["status"] = "activated"
            p["licType"] = LICENSE_TYPE
            if "users" in p: p["users"] = MAX_USERS
        if "users" in L[m]: L[m]["users"] = MAX_USERS
    
    for mod in ["ipsec","updateSoft","kylinOS","distributedCluster"]:
        if mod in L:
            L[mod][mod + "ExpireTime"] = Y
            L[mod]["status"] = "activated"
            if mod + "IsUnlimited" in L[mod]: L[mod][mod + "IsUnlimited"] = True
    
    M = data.get("module", {})
    for mn in M:
        for fn in M[mn]:
            f = M[mn][fn]
            f["status"] = "activated"; f["expireTime"] = Y; f["isUnlimited"] = True
            if "users" in f: f["users"] = MAX_USERS
            for p in (f.get("parts") or []):
                p["status"] = "activated"; p["expireTime"] = Y; p["isUnlimited"] = True
                p["licType"] = LICENSE_TYPE
                if "users" in p: p["users"] = MAX_USERS
    
    data["devDeadline"] = 99999
    
    json_str = json.dumps(data, ensure_ascii=False)
    run(f"{ETCD} put /config/private/license/local '{json_str}'")
    log("etcd 授权数据写入成功")
    return True

