def fix_daemon_config():
    if not os.path.exists(PATHS["daemon_config"]):
        warn("daemon 配置文件不存在")
        return False
    try:
        with open(PATHS["daemon_config"]) as f:
            cfg = json.load(f)
        cfg["checkLicenseInterval"] = 999999999
        with open(PATHS["daemon_config"], "w") as f:
            json.dump(cfg, f, indent=4)
        log("daemon checkLicenseInterval 已设为 31年")
        copy_config_to_container()
        return True
    except Exception as e:
        warn(f"修改 daemon 配置失败: {e}")
        return False

