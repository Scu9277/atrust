def verify():
    out, _, _ = run(f"{PATHS['etcdctl']} get /config/private/license/local --print-value-only")
    if not out: return False
    try:
        d = json.loads(out)
        l = d["license"]
        b = l.get("base", {})
        ok = True
        print("\n" + "=" * 50)
        print("  授权验证结果")
        print("=" * 50)
        print(f"  授权类型: {l.get('licenseType')}")
        print(f"  客户名称: {l.get('customerName')}")
        print(f"  授权状态: {l.get('status')}")
        print(f"  基础用户: {b.get('users')}")
        print(f"  无限期: {b.get('baseIsUnlimited')}")
        print(f"  到期时间戳: {b.get('baseExpireTime')}")
        print("=" * 50)
        if l.get("licenseType") != LICENSE_TYPE: ok = False
        if b.get("baseIsUnlimited") != True: ok = False
        if b.get("users") != MAX_USERS: ok = False
        return ok
    except:
        return False

